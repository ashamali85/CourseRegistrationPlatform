import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

/**
 * Builds a TYPED stand-in for the generated Prisma client by parsing
 * schema.prisma.
 *
 * The sandbox cannot reach binaries.prisma.sh, so `prisma generate` is
 * unavailable and the obvious workaround — stubbing every model as `any` —
 * silently accepts nonsense like `slot.courseId` after that column has moved.
 * That is a false green: it type-checks locally and then fails the real build.
 *
 * Relations are emitted as non-optional, so reading one without `include`
 * passes (a deliberate false negative), while reading a field that does not
 * exist on the model at all is a hard error. That is the class of mistake a
 * schema change actually introduces.
 */
const SCALARS = {
  String: 'string',
  Int: 'number',
  Float: 'number',
  Boolean: 'boolean',
  DateTime: 'Date',
  Json: 'any',
  Decimal: 'any',
  BigInt: 'bigint',
  Bytes: 'any'
};

const schema = readFileSync('prisma/schema.prisma', 'utf8');

// Strip comments so they cannot be mistaken for field lines.
const clean = schema
  .split('\n')
  .map((line) => line.replace(/\/\/.*$/, ''))
  .join('\n');

const models = [...clean.matchAll(/model\s+(\w+)\s*\{([\s\S]*?)\n\}/g)].map(
  ([, name, body]) => {
    const fields = [];
    for (const raw of body.split('\n')) {
      const line = raw.trim();
      if (!line || line.startsWith('@@')) continue;

      const match = line.match(/^(\w+)\s+(\w+)(\[\])?(\?)?/);
      if (!match) continue;

      const [, fieldName, typeName, isList, isOptional] = match;
      const mapped = SCALARS[typeName] ?? typeName;

      let ts = mapped;
      if (isList) ts = `${mapped}[]`;
      // A list relation is never null; an optional scalar or relation is.
      else if (isOptional) ts = `${mapped} | null`;

      fields.push(`  ${fieldName}: ${ts};`);
    }
    return { name, fields };
  }
);

const modelTypes = models
  .map(
    (m) => `export type ${m.name} = {\n${m.fields.join('\n')}\n  _count: any;\n};`
  )
  .join('\n\n');

const delegate = (name) => `{
    findUnique(args?: any): Promise<${name} | null>;
    findUniqueOrThrow(args?: any): Promise<${name}>;
    findFirst(args?: any): Promise<${name} | null>;
    findMany(args?: any): Promise<${name}[]>;
    create(args?: any): Promise<${name}>;
    createMany(args?: any): Promise<{ count: number }>;
    update(args?: any): Promise<${name}>;
    updateMany(args?: any): Promise<{ count: number }>;
    upsert(args?: any): Promise<${name}>;
    delete(args?: any): Promise<${name}>;
    deleteMany(args?: any): Promise<{ count: number }>;
    count(args?: any): Promise<number>;
    groupBy(args?: any): Promise<any[]>;
    aggregate(args?: any): Promise<any>;
  }`;

const lower = (s) => s.charAt(0).toLowerCase() + s.slice(1);

const clientFields = models
  .map((m) => `  ${lower(m.name)}: ${delegate(m.name)};`)
  .join('\n');

const output = `// GENERATED by scripts/gen-prisma-stub.mjs — do not edit.
// Typed stand-in for @prisma/client used only for local typechecking.
declare module '@prisma/client' {
${modelTypes
  .split('\n')
  .map((l) => (l ? '  ' + l : l))
  .join('\n')}

  export class PrismaClient {
    constructor(...args: any[]);
${clientFields}
    $transaction<T>(
      arg: ((tx: PrismaClient) => Promise<T>) | any[],
      options?: any
    ): Promise<T>;
    $queryRaw(...args: any[]): Promise<any>;
    $executeRaw(...args: any[]): Promise<any>;
    $disconnect(): Promise<void>;
    $connect(): Promise<void>;
  }

  export namespace Prisma {
    class PrismaClientKnownRequestError extends Error {
      code: string;
      meta?: any;
    }
    class PrismaClientValidationError extends Error {}
    const TransactionIsolationLevel: {
      ReadUncommitted: 'ReadUncommitted';
      ReadCommitted: 'ReadCommitted';
      RepeatableRead: 'RepeatableRead';
      Serializable: 'Serializable';
    };
  }
}
`;

mkdirSync('.typecheck-stub', { recursive: true });
writeFileSync('.typecheck-stub/prisma-stub.d.ts', output);

console.log(`Generated stub for ${models.length} models:`);
for (const m of models) console.log(`  ${m.name} (${m.fields.length} fields)`);
